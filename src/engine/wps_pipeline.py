#!/usr/bin/env python3
"""
CycloCast NWP - WPS Preprocessing Pipeline (Phase 2)
Automates geogrid.exe, link_grib.csh, ungrib.exe, and metgrid.exe execution.
Enforces validation checks at each stage before permitting real.exe initialization.
"""

import os
import sys
import subprocess
import glob
from pathlib import Path
from datetime import datetime, timezone

class WPSPipeline:
    def __init__(self, wps_dir: str, work_dir: str, gfs_dir: str):
        self.wps_dir = Path(wps_dir)
        self.work_dir = Path(work_dir)
        self.gfs_dir = Path(gfs_dir)
        self.work_dir.mkdir(parents=True, exist_ok=True)

    def log(self, message: str, level: str = "INFO"):
        now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
        print(f"[{now}] [{level}] [WPS] {message}")

    def run_command(self, cmd: list[str], log_filename: str) -> bool:
        log_path = self.work_dir / log_filename
        self.log(f"Executing: {' '.join(cmd)} > {log_filename}")
        with open(log_path, "w") as log_f:
            result = subprocess.run(cmd, cwd=self.work_dir, stdout=log_f, stderr=subprocess.STDOUT)
            if result.returncode != 0:
                self.log(f"Command failed with exit code {result.returncode}. Inspect {log_path}", level="ERROR")
                return False
        return True

    def run_geogrid(self) -> bool:
        self.log("Step 1: Running geogrid.exe for domain topography & landuse interpolation...")
        geogrid_exe = self.wps_dir / "geogrid.exe"
        if not geogrid_exe.exists():
            self.log(f"geogrid.exe not found at {geogrid_exe}", level="ERROR")
            return False
        
        # Link geogrid binary and tables
        os.system(f"ln -sf {self.wps_dir}/geogrid.exe {self.work_dir}/")
        os.system(f"ln -sf {self.wps_dir}/geogrid {self.work_dir}/")

        success = self.run_command(["./geogrid.exe"], "geogrid.log")
        if not success: return False

        # Validate outputs
        geo_files = list(self.work_dir.glob("geo_em.d*.nc"))
        if not geo_files:
            self.log("FATAL: No geo_em files generated by geogrid.exe", level="ERROR")
            return False
        self.log(f"✓ geogrid.exe completed successfully. Generated {len(geo_files)} domain static file(s).", level="SUCCESS")
        return True

    def run_ungrib(self) -> bool:
        self.log("Step 2: Linking GRIB2 files and executing ungrib.exe...")
        gfs_files = sorted(glob.glob(str(self.gfs_dir / "gfs.*.pgrb2.0p25*")))
        if not gfs_files:
            self.log(f"No GFS GRIB2 files found in {self.gfs_dir}", level="ERROR")
            return False

        # Link files using link_grib.csh
        link_cmd = f"csh {self.wps_dir}/link_grib.csh {' '.join(gfs_files)}"
        subprocess.run(link_cmd, shell=True, cwd=self.work_dir)

        # Link Vtable for GFS
        vtable_path = self.wps_dir / "ungrib" / "Variable_Tables" / "Vtable.GFS"
        os.system(f"ln -sf {vtable_path} {self.work_dir}/Vtable")
        os.system(f"ln -sf {self.wps_dir}/ungrib.exe {self.work_dir}/")

        success = self.run_command(["./ungrib.exe"], "ungrib.log")
        if not success: return False

        ungrib_files = list(self.work_dir.glob("FILE:*"))
        if not ungrib_files:
            self.log("FATAL: No intermediate FILE:* records generated by ungrib.exe", level="ERROR")
            return False
        self.log(f"✓ ungrib.exe completed successfully. Generated {len(ungrib_files)} intermediate boundary time slices.", level="SUCCESS")
        return True

    def run_metgrid(self) -> bool:
        self.log("Step 3: Running metgrid.exe to interpolate boundary data onto model grid...")
        os.system(f"ln -sf {self.wps_dir}/metgrid.exe {self.work_dir}/")
        os.system(f"ln -sf {self.wps_dir}/metgrid {self.work_dir}/")

        success = self.run_command(["./metgrid.exe"], "metgrid.log")
        if not success: return False

        met_files = list(self.work_dir.glob("met_em.d01.*.nc"))
        if not met_files:
            self.log("FATAL: No met_em.d01 files produced by metgrid.exe", level="ERROR")
            return False
        self.log(f"✓ metgrid.exe completed successfully. Generated {len(met_files)} meteorological grid files.", level="SUCCESS")
        return True

    def execute_all(self) -> bool:
        self.log("Beginning WPS meteorological preprocessing pipeline...")
        if not self.run_geogrid(): return False
        if not self.run_ungrib(): return False
        if not self.run_metgrid(): return False
        self.log("All WPS preprocessing stages completed. Ready for real.exe execution.", level="SUCCESS")
        return True

if __name__ == "__main__":
    wps = WPSPipeline(
        wps_dir=os.environ.get("WPS_DIR", "/opt/cyclocast/WPS"),
        work_dir=os.environ.get("RUN_DIR", "/opt/cyclocast/runs/test_run"),
        gfs_dir=os.environ.get("GFS_DIR", "/opt/cyclocast/incoming_gfs")
    )
    if not wps.execute_all():
        sys.exit(1)
